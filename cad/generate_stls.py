#!/usr/bin/env python3
"""
Python Binary STL Generator for Pebble Wall Clock
Zero-dependency, pure Python 3 script to export 3D printable meshes.
"""

import os
import math
import struct

def vec_sub(a, b):
    return (a[0]-b[0], a[1]-b[1], a[2]-b[2])

def vec_cross(a, b):
    return (
        a[1]*b[2] - a[2]*b[1],
        a[2]*b[0] - a[0]*b[2],
        a[0]*b[1] - a[1]*b[0]
    )

def vec_norm(v):
    l = math.sqrt(v[0]**2 + v[1]**2 + v[2]**2)
    if l == 0:
        return (0.0, 0.0, 1.0)
    return (v[0]/l, v[1]/l, v[2]/l)

class Mesh:
    def __init__(self, name="Mesh"):
        self.name = name
        self.triangles = [] # list of ((nx,ny,nz), v1, v2, v3)

    def add_triangle(self, v1, v2, v3):
        e1 = vec_sub(v2, v1)
        e2 = vec_sub(v3, v1)
        n = vec_norm(vec_cross(e1, e2))
        self.triangles.append((n, v1, v2, v3))

    def add_quad(self, v1, v2, v3, v4):
        # v1, v2, v3, v4 in counter-clockwise order
        self.add_triangle(v1, v2, v3)
        self.add_triangle(v1, v3, v4)

    def add_box(self, cx, cy, cz, w, l, h):
        x0, x1 = cx - w/2, cx + w/2
        y0, y1 = cy - l/2, cy + l/2
        z0, z1 = cz - h/2, cz + h/2

        # 8 vertices
        v000 = (x0, y0, z0)
        v100 = (x1, y0, z0)
        v110 = (x1, y1, z0)
        v010 = (x0, y1, z0)
        v001 = (x0, y0, z1)
        v101 = (x1, y0, z1)
        v111 = (x1, y1, z1)
        v011 = (x0, y1, z1)

        # Bottom (z0)
        self.add_quad(v000, v100, v110, v010)
        # Top (z1)
        self.add_quad(v001, v011, v111, v101)
        # Front (y0)
        self.add_quad(v000, v001, v101, v100)
        # Back (y1)
        self.add_quad(v110, v111, v011, v010)
        # Left (x0)
        self.add_quad(v010, v011, v001, v000)
        # Right (x1)
        self.add_quad(v100, v101, v111, v110)

    def add_cylinder(self, cx, cy, cz, r, h, segments=32):
        z0 = cz - h/2
        z1 = cz + h/2
        top_pts = []
        bot_pts = []
        for i in range(segments):
            theta = 2.0 * math.pi * i / segments
            x = cx + r * math.cos(theta)
            y = cy + r * math.sin(theta)
            bot_pts.append((x, y, z0))
            top_pts.append((x, y, z1))

        # Side walls
        for i in range(segments):
            next_i = (i + 1) % segments
            self.add_quad(bot_pts[i], top_pts[i], top_pts[next_i], bot_pts[next_i])

        # Bottom cap
        bot_center = (cx, cy, z0)
        for i in range(segments):
            next_i = (i + 1) % segments
            self.add_triangle(bot_center, bot_pts[next_i], bot_pts[i])

        # Top cap
        top_center = (cx, cy, z1)
        for i in range(segments):
            next_i = (i + 1) % segments
            self.add_triangle(top_center, top_pts[i], top_pts[next_i])

    def export_stl(self, filepath):
        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, 'wb') as f:
            # 80 bytes header
            header = f"Binary STL generated by Bug91Dub Python Generator: {self.name}".encode('ascii')
            header = header[:80].ljust(80, b'\0')
            f.write(header)
            # Triangle count
            f.write(struct.pack('<I', len(self.triangles)))
            # Triangles
            for n, v1, v2, v3 in self.triangles:
                f.write(struct.pack('<3f3f3f3fH',
                    n[0], n[1], n[2],
                    v1[0], v1[1], v1[2],
                    v2[0], v2[1], v2[2],
                    v3[0], v3[1], v3[2],
                    0
                ))
        print(f"Exported: {filepath} ({len(self.triangles)} triangles, {os.path.getsize(filepath)/1024:.1f} KB)")


def make_rounded_rect_pts(w, h, r, segments_per_corner=8):
    pts = []
    corners = [
        ( w/2 - r,  h/2 - r, 0),
        (-w/2 + r,  h/2 - r, math.pi/2),
        (-w/2 + r, -h/2 + r, math.pi),
        ( w/2 - r, -h/2 + r, 3*math.pi/2)
    ]
    for cx, cy, start_angle in corners:
        for i in range(segments_per_corner):
            theta = start_angle + (math.pi/2) * (i / segments_per_corner)
            pts.append((cx + r * math.cos(theta), cy + r * math.sin(theta)))
    return pts


def generate_button_caps():
    mesh = Mesh("Pebble_Button_Caps")
    # Generates 4 side button caps
    btn_w = 6.0
    btn_l = 22.0
    btn_h = 9.0
    for idx in range(4):
        x_off = idx * 14.0 - 21.0
        # Main cap
        mesh.add_box(x_off, 0, btn_h/2, btn_w, btn_l - 4, btn_h)
        # Flange base
        mesh.add_box(x_off, 0, 1.0, btn_w + 2.0, btn_l, 2.0)
    return mesh


def generate_desk_stand():
    mesh = Mesh("Pebble_Desk_Stand")
    stand_w = 71.0 # Fits inside 72mm lug gap
    stand_l = 85.0
    stand_t = 7.0
    angle = math.radians(18.0)

    # Base foot
    mesh.add_box(0, -stand_l/2, stand_t/2, stand_w, stand_l, stand_t)
    # Lug engagement hinge block
    mesh.add_box(0, 0, 9.0, stand_w, 16.0, 18.0)
    # Engagement pins (4.6mm dia cylinders)
    mesh.add_cylinder(-stand_w/2, 0, 10.0, 2.3, 16.0)
    mesh.add_cylinder( stand_w/2, 0, 10.0, 2.3, 16.0)
    return mesh


def generate_front_bezel():
    mesh = Mesh("Pebble_Front_Bezel")
    # Nook dimensions
    nook_w, nook_h, nook_d = 127.0, 165.0, 12.0
    body_w = nook_w + 1.2 + 28.0 # 156.2 mm
    body_h = nook_h + 1.2 + 32.0 # 198.2 mm
    depth = 9.0
    screen_w = 91.5
    screen_h = 123.5
    corner_r = 18.0

    # We build the frame from 4 border sections around the central screen window:
    # Left border, Right border, Top border, Bottom border
    x_in_left = -screen_w/2
    x_in_right = screen_w/2
    y_in_bot = -screen_h/2
    y_in_top = screen_h/2

    x_out_left = -body_w/2
    x_out_right = body_w/2
    y_out_bot = -body_h/2
    y_out_top = body_h/2

    # Left frame slab
    mesh.add_box((x_out_left + x_in_left)/2, 0, depth/2, (x_in_left - x_out_left), body_h, depth)
    # Right frame slab
    mesh.add_box((x_out_right + x_in_right)/2, 0, depth/2, (x_out_right - x_in_right), body_h, depth)
    # Top frame slab
    mesh.add_box(0, (y_out_top + y_in_top)/2, depth/2, screen_w, (y_out_top - y_in_top), depth)
    # Bottom frame slab
    mesh.add_box(0, (y_out_bot + y_in_bot)/2, depth/2, screen_w, (y_in_bot - y_out_bot), depth)

    # Top & Bottom Strap Lugs
    lug_ext = 22.0
    lug_w = 18.0
    lug_spacing = 72.0
    for dir_y in [-1, 1]:
        cy = dir_y * (body_h/2 + lug_ext/2)
        # Left horn
        mesh.add_box(-lug_spacing/2 - lug_w/2, cy, depth/2, lug_w, lug_ext, depth)
        # Right horn
        mesh.add_box( lug_spacing/2 + lug_w/2, cy, depth/2, lug_w, lug_ext, depth)

    return mesh


def generate_rear_mount():
    mesh = Mesh("Pebble_Rear_Mount")
    nook_w, nook_h, nook_d = 127.0, 165.0, 12.0
    body_w = nook_w + 1.2 + 28.0 # 156.2 mm
    body_h = nook_h + 1.2 + 32.0 # 198.2 mm
    depth = 15.0
    base_t = 3.5 # Solid back wall thickness
    rim_w = 14.0 # Perimeter rim clamping Nook

    # Back plate base
    mesh.add_box(0, 0, base_t/2, body_w, body_h, base_t)

    # Perimeter retention walls (forming pocket for Nook)
    pocket_w = nook_w + 1.2
    pocket_h = nook_h + 1.2
    rim_h = depth - base_t
    cz = base_t + rim_h/2

    # Left & Right side walls
    wall_w = (body_w - pocket_w) / 2
    mesh.add_box(-body_w/2 + wall_w/2, 0, cz, wall_w, body_h, rim_h)
    mesh.add_box( body_w/2 - wall_w/2, 0, cz, wall_w, body_h, rim_h)

    # Top wall
    wall_h = (body_h - pocket_h) / 2
    mesh.add_box(0, body_h/2 - wall_h/2, cz, pocket_w, wall_h, rim_h)

    # Bottom wall (with 16mm micro-USB cable notch in center)
    cable_notch_w = 16.0
    sub_wall_w = (pocket_w - cable_notch_w) / 2
    mesh.add_box(-cable_notch_w/2 - sub_wall_w/2, -body_h/2 + wall_h/2, cz, sub_wall_w, wall_h, rim_h)
    mesh.add_box( cable_notch_w/2 + sub_wall_w/2, -body_h/2 + wall_h/2, cz, sub_wall_w, wall_h, rim_h)

    # Top & Bottom Strap Lugs
    lug_ext = 22.0
    lug_w = 18.0
    lug_spacing = 72.0
    for dir_y in [-1, 1]:
        cy = dir_y * (body_h/2 + lug_ext/2)
        mesh.add_box(-lug_spacing/2 - lug_w/2, cy, depth/2, lug_w, lug_ext, depth)
        mesh.add_box( lug_spacing/2 + lug_w/2, cy, depth/2, lug_w, lug_ext, depth)

    return mesh


